// Convert the next.config.mjs `redirects` + `rewrites` arrays into a
// Cloudflare Pages `_redirects` file (placed under public/ so Next's
// static export carries it into out/).
//
// Cloudflare `_redirects` format:
//   /source/path   /destination/path   30x
//   /source        /destination         200    (rewrite/proxy)
//
// Splat support is `:splat` (Cloudflare) vs `:path*` (Next). Param
// names with single segments (`:id`) work the same in both.

import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO = join(__dirname, '..');

const cfg = await import(join(REPO, 'next.config.mjs'));
// next.config.mjs default-exports a Next config. Some configs wrap
// it (e.g. through withMDX) but the resulting object preserves
// `redirects` and `rewrites` async functions.
const conf = cfg.default;

const redirects = await conf.redirects?.() ?? [];
const rewrites = await conf.rewrites?.() ?? [];

// Convert Next path params to Cloudflare splat / params.
//   :path*   →  :splat        (only one splat per rule, Cloudflare)
//   :id      →  :id           (single-segment param, same syntax)
function toCloudflarePath(p) {
  return p.replace(/:([a-zA-Z]+)\*/g, ':splat');
}

const lines = [
  '# Generated by scripts/gen-redirects.mjs from next.config.mjs',
  '# Do not edit by hand — re-run `npm run gen:redirects` after',
  '# changing the redirects/rewrites arrays in next.config.mjs.',
  '',
];

for (const r of redirects) {
  const status = r.permanent ? 301 : 302;
  lines.push(
    `${toCloudflarePath(r.source)}  ${toCloudflarePath(r.destination)}  ${status}`,
  );
}

if (rewrites.length > 0) {
  lines.push('');
  lines.push('# Rewrites (proxy / no redirect — status 200)');
}
for (const r of rewrites) {
  lines.push(
    `${toCloudflarePath(r.source)}  ${toCloudflarePath(r.destination)}  200`,
  );
}

const out = join(REPO, 'public', '_redirects');
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, lines.join('\n') + '\n');
console.log(
  `Wrote ${redirects.length} redirects + ${rewrites.length} rewrites to ${out}`,
);
